//! `agentdeck-daemon.service` systemd user unit: install/remove/inspect.
//!
//! Install renders the unit file and runs `systemctl --user daemon-reload`
//! only. It NEVER enables or starts anything: the owner enables the unit by
//! hand at cutover (see docs/MIGRATION.md).

use std::env;
use std::path::PathBuf;
use std::process::Command;

use crate::changes::Change;
use crate::paths::Paths;

pub const UNIT_NAME: &str = "agentdeck-daemon.service";
const UNIT_TEMPLATE: &str = include_str!("../../../systemd/agentdeck-daemon.service.in");
// Guard so uninstall never deletes a file it did not generate.
const GENERATED_MARKER: &str = "Generated by `agentdeck service install`";

fn systemctl_cmd() -> String {
    env::var("AGENTDECK_SYSTEMCTL").unwrap_or_else(|_| "systemctl".to_owned())
}

/// `~/.config/systemd/user`, honoring `XDG_CONFIG_HOME` so tests run on temp dirs.
fn systemd_user_dir() -> anyhow::Result<PathBuf> {
    if let Some(dir) = env::var_os("XDG_CONFIG_HOME") {
        return Ok(PathBuf::from(dir).join("systemd/user"));
    }
    let home = env::var_os("HOME").map(PathBuf::from).ok_or_else(|| {
        anyhow::anyhow!("cannot resolve config home: set HOME or XDG_CONFIG_HOME")
    })?;
    Ok(home.join(".config/systemd/user"))
}

pub fn unit_path() -> anyhow::Result<PathBuf> {
    Ok(systemd_user_dir()?.join(UNIT_NAME))
}

fn render_unit(paths: &Paths) -> anyhow::Result<Vec<u8>> {
    let exe = env::current_exe()?;
    let bin_dir = exe
        .parent()
        .ok_or_else(|| anyhow::anyhow!("current exe has no parent dir"))?;
    let secrets = paths.config_dir.join("usage.env");
    Ok(UNIT_TEMPLATE
        .replace("@BINARY@", &exe.to_string_lossy())
        .replace("@BIN_DIR@", &bin_dir.to_string_lossy())
        .replace("@SECRETS@", &secrets.to_string_lossy())
        .into_bytes())
}

fn daemon_reload() -> anyhow::Result<()> {
    let out = Command::new(systemctl_cmd())
        .arg("--user")
        .arg("daemon-reload")
        .output()?;
    if !out.status.success() {
        anyhow::bail!(
            "systemctl --user daemon-reload failed: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(())
}

/// True while the new unit is active. Missing systemctl counts as inactive.
pub fn unit_active() -> bool {
    match Command::new(systemctl_cmd())
        .arg("--user")
        .arg("is-active")
        .arg(UNIT_NAME)
        .output()
    {
        Ok(out) => out.status.success() && String::from_utf8_lossy(&out.stdout).trim() == "active",
        Err(_) => false,
    }
}

/// Plan the install: `None` when already up to date (no reload then either).
pub fn plan_install(paths: &Paths) -> anyhow::Result<Option<Change>> {
    let path = unit_path()?;
    let new = render_unit(paths)?;
    let old = std::fs::read(&path).ok();
    if old.as_deref() == Some(new.as_slice()) {
        return Ok(None);
    }
    Ok(Some(Change::WriteFile {
        path,
        contents: new,
        old,
        backup: None,
    }))
}

/// Apply install changes, then reload (never enable/start).
pub fn apply_install(changes: &[Change]) -> anyhow::Result<()> {
    crate::changes::apply_changes(changes)?;
    daemon_reload()
}

/// Plan the removal: `None` when not installed. Refuses while the unit is
/// active, or when the file was not generated by agentdeck.
pub fn plan_uninstall() -> anyhow::Result<Option<Change>> {
    let path = unit_path()?;
    if unit_active() {
        anyhow::bail!(
            "refusing: {UNIT_NAME} is active; ask the owner to run \
             `systemctl --user stop {UNIT_NAME}` first"
        );
    }
    let old = match std::fs::read(&path) {
        Ok(bytes) => bytes,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(e.into()),
    };
    if !String::from_utf8_lossy(&old).contains(GENERATED_MARKER) {
        anyhow::bail!(
            "{} exists but was not generated by agentdeck; remove it by hand",
            path.display()
        );
    }
    Ok(Some(Change::Remove { path }))
}

/// Apply removal changes, then reload.
pub fn apply_uninstall(changes: &[Change]) -> anyhow::Result<()> {
    crate::changes::apply_changes(changes)?;
    daemon_reload()
}

pub struct UnitStatus {
    pub path: PathBuf,
    pub installed: bool,
    pub up_to_date: bool,
    pub active: bool,
}

/// Read-only status: never shells out beyond the is-active probe.
pub fn status(paths: &Paths) -> anyhow::Result<UnitStatus> {
    let path = unit_path()?;
    let installed = std::fs::read(&path).ok();
    Ok(UnitStatus {
        path,
        installed: installed.is_some(),
        up_to_date: installed.as_deref() == render_unit(paths).ok().as_deref(),
        active: unit_active(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::os::unix::fs::PermissionsExt;
    use std::sync::atomic::{AtomicU64, Ordering};

    static N: AtomicU64 = AtomicU64::new(0);

    struct Guard(PathBuf);
    impl Drop for Guard {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    /// Temp HOME with a fake systemctl that answers is-active from
    /// `$FAKE_SYSTEMCTL_ACTIVE` and logs every other invocation to
    /// `$FAKE_SYSTEMCTL_LOG`. Returns (guard, log path). Callers hold
    /// [`crate::plugins::test_env_lock`] across the whole test body.
    fn fake_home(active: &str) -> (Guard, PathBuf) {
        let dir = std::env::temp_dir().join(format!(
            "agentdeck-service-{}-{}",
            std::process::id(),
            N.fetch_add(1, Ordering::SeqCst)
        ));
        let _ = fs::remove_dir_all(&dir);
        let script = dir.join("systemctl");
        fs::create_dir_all(&dir).unwrap();
        fs::write(
            &script,
            "#!/bin/sh\n\
             if [ \"$1\" = \"--user\" ] && [ \"$2\" = \"is-active\" ]; then\n\
             echo \"$FAKE_SYSTEMCTL_ACTIVE\"\n\
             [ \"$FAKE_SYSTEMCTL_ACTIVE\" = \"active\" ]\n\
             exit\n\
             fi\n\
             echo \"$@\" >> \"$FAKE_SYSTEMCTL_LOG\"\n",
        )
        .unwrap();
        fs::set_permissions(&script, fs::Permissions::from_mode(0o755)).unwrap();
        unsafe {
            env::set_var("XDG_CONFIG_HOME", dir.join("config"));
            env::set_var("AGENTDECK_SYSTEMCTL", &script);
            env::set_var("FAKE_SYSTEMCTL_ACTIVE", active);
            env::set_var("FAKE_SYSTEMCTL_LOG", dir.join("calls.log"));
        }
        let log = dir.join("calls.log");
        (Guard(dir), log)
    }

    fn test_paths(home: &std::path::Path) -> Paths {
        Paths::new(home.join("config/agentdeck"), home.join("state/agentdeck"))
    }

    #[test]
    fn install_renders_reloads_never_enables_uninstall_refuses_while_active() {
        let _env = crate::plugins::test_env_lock();
        let (_g, log) = fake_home("inactive");
        let home = _g.0.clone();
        let paths = test_paths(&home);
        let unit = home.join("config/systemd/user/agentdeck-daemon.service");

        // Planning renders but writes nothing and reloads nothing.
        assert!(plan_install(&paths).unwrap().is_some());
        assert!(!unit.exists());
        assert!(!log.exists());

        // Real install writes the unit and reloads exactly once.
        let changes = vec![plan_install(&paths).unwrap().unwrap()];
        apply_install(&changes).unwrap();
        let text = fs::read_to_string(&unit).unwrap();
        assert!(text.contains("\"") && text.contains("daemon"), "{text}");
        assert!(!text.contains('@'), "{text}");
        assert!(!text.contains("mise"), "{text}");
        assert!(text.contains("usage.env"), "{text}");
        let calls = fs::read_to_string(&log).unwrap();
        assert!(calls.contains("daemon-reload"), "{calls}");
        assert!(!calls.contains("enable"), "{calls}");
        assert!(!calls.contains("start"), "{calls}");

        // Status is read-only: no new systemctl calls beyond is-active probes.
        fs::remove_file(&log).ok();
        let st = status(&paths).unwrap();
        assert!(st.installed && st.up_to_date && !st.active);
        assert!(!log.exists());

        // Uninstall refuses while the unit is active, file stays.
        unsafe {
            env::set_var("FAKE_SYSTEMCTL_ACTIVE", "active");
        }
        assert!(plan_uninstall().is_err());
        assert!(unit.exists());

        // Inactive: plan-None keeps the file, apply removes it + reloads.
        unsafe {
            env::set_var("FAKE_SYSTEMCTL_ACTIVE", "inactive");
        }
        let changes = vec![plan_uninstall().unwrap().unwrap()];
        assert!(unit.exists());
        apply_uninstall(&changes).unwrap();
        assert!(!unit.exists());
        let calls = fs::read_to_string(&log).unwrap();
        assert!(calls.contains("daemon-reload"), "{calls}");
    }
}
